# Bug types are stored in display form already, so only statuses, outcomes and severities need labels.
TERMS: dict[str, str] = {
    "informational": "Informational",
    "low": "Low",
    "medium": "Medium",
    "high": "High",
    "critical": "Critical",
    "draft": "Draft",
    "submitted": "Submitted",
    "processing": "Processing",
    "done": "Done",
    "accepted": "Accepted",
    "rejected": "Rejected",
    "duplicate": "Duplicate",
    "informative": "Informative",
    "out_of_scope": "Out of scope",
    "archived": "Archived",
}


def term(value: object) -> str:
    """Display label for a stored status or severity; unknown snake_case values are humanized."""
    if value is None or value == "":
        return ""
    key = str(value)
    if key in TERMS:
        return TERMS[key]
    # Values that are already cased, such as "OAuth / SSO", are returned as is.
    if "_" in key or key.islower():
        return key.replace("_", " ").capitalize()
    return key
